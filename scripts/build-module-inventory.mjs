#!/usr/bin/env node
// Builds src/language/moduleInventory.generated.js: the real module, file and
// class names under src/, used by the chat attribution guarantee (contract
// v4): an answer may not name a module the repository does not have.
//
// Usage: node scripts/build-module-inventory.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src');
const OUT = path.join(SRC, 'language', 'moduleInventory.generated.js');
const check = process.argv.includes('--check');

export function scanModuleNames(srcDir = SRC) {
  const files = [];
  const paths = [];
  const names = new Set();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) { if (entry.name !== 'node_modules') walk(full); continue; }
      if (!/\.(js|jsx|mjs|cjs)$/.test(entry.name) || entry.name.endsWith('.generated.js')) continue;
      files.push(entry.name);
      paths.push(`src/${path.relative(srcDir, full).split(path.sep).join('/')}`);
      names.add(entry.name.replace(/\.(js|jsx|mjs|cjs)$/, ''));
      const text = fs.readFileSync(full, 'utf8');
      for (const m of text.matchAll(/\bclass\s+([A-Z][A-Za-z0-9_]*)/g)) names.add(m[1]);
      for (const m of text.matchAll(/\bexport\s+(?:const|function)\s+([A-Z][A-Za-z0-9_]*)/g)) names.add(m[1]);
    }
  };
  walk(srcDir);
  return { files: [...new Set(files)].sort(), paths: [...new Set(paths)].sort(), names: [...names].sort() };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
if (isMain) {
  const { files, paths, names } = scanModuleNames();
  const body = `// GENERATED by scripts/build-module-inventory.mjs — do not edit by hand.
// Real file, module and class names under src/ (attribution guarantee, contract v4).
export const MODULE_FILES = Object.freeze(${JSON.stringify(files)});
export const MODULE_PATHS = Object.freeze(${JSON.stringify(paths)});
export const MODULE_NAMES = Object.freeze(${JSON.stringify(names)});
`;
  if (check) {
    // Git's Windows autocrlf checkout must not make an unchanged inventory stale.
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== body) { console.error('[module-inventory] stale; run node scripts/build-module-inventory.mjs'); process.exit(1); }
    console.log('[module-inventory] up to date');
  } else {
    fs.writeFileSync(OUT, body);
    console.log(JSON.stringify({ out: path.relative(ROOT, OUT), files: files.length, paths: paths.length, names: names.length }));
  }
}
